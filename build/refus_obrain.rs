//! Generator of the refusals of the obrain backend (feature `obrain-backend`).
//!
//! The obrain backend is ported one domain at a time. Until a domain is
//! ported, every method of its trait must answer a NAMED error — never an
//! empty result, never a panic. The store contracts hold ~760 methods; writing
//! those refusals by hand would duplicate the contract and rot with it.
//!
//! So this build step READS the contracts (`src/neo4j/traits.rs`,
//! `src/meilisearch/traits.rs`) and writes, into `$OUT_DIR/obrain_refus.rs`,
//! one `impl <Trait> for <Target>` per trait that `src/obrain/` does not
//! implement by hand. Each generated method keeps the exact signature of the
//! contract and returns `Err(NonPorte("<Trait>::<method>"))`.
//!
//! What decides "ported": a hand-written `impl <Trait> for <Target>` anywhere
//! in `src/obrain/`. Nothing to keep in sync — porting a domain is writing its
//! impl, and the generator stops emitting the refusals of that trait.
//!
//! Rules, enforced here (a violation fails the build and names the method):
//! - a method that returns `Result` is refused, **including when the contract
//!   gives it a default body** (a default that answers `Ok(vec![])` would be
//!   the silent empty result this backend must never give);
//! - a method that does not return `Result` cannot carry a refusal: it is
//!   accepted only if the contract gives it a default, which is then kept and
//!   listed in `DEFAUTS_CONSERVES`;
//! - anything else in a trait (associated type, constant) is unsupported.

use quote::ToTokens;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// One contract file and the type that implements it for obrain.
struct Contrat {
    /// The file holding the traits, relative to the crate root.
    fichier: &'static str,
    /// Module path of that file: its own items are glob-imported.
    module: &'static str,
    /// What a leading `super` means in the `use` lines of that file.
    parent: &'static str,
    /// The implementing type, as a path.
    cible: &'static str,
    /// Name of the generated module.
    nom: &'static str,
}

const CONTRATS: &[Contrat] = &[
    Contrat {
        fichier: "src/neo4j/traits.rs",
        module: "crate::neo4j::traits",
        parent: "crate::neo4j",
        cible: "crate::obrain::ObrainGraphStore",
        nom: "graphe",
    },
    Contrat {
        fichier: "src/meilisearch/traits.rs",
        module: "crate::meilisearch::traits",
        parent: "crate::meilisearch",
        cible: "crate::obrain::ObrainSearchStore",
        nom: "recherche",
    },
];

/// Where the hand-written implementations live.
const ADAPTATEUR: &str = "src/obrain";

pub fn generer(racine: &Path, sortie: &Path) {
    println!("cargo:rerun-if-changed=build/refus_obrain.rs");
    println!("cargo:rerun-if-changed={ADAPTATEUR}");

    let portes = impls_ecrits_a_la_main(&racine.join(ADAPTATEUR));

    let mut code = String::from(
        "// GENERATED by build/refus_obrain.rs from the store contracts. Do not edit.\n",
    );
    let mut refusees: Vec<String> = Vec::new();
    let mut portees: Vec<String> = Vec::new();
    let mut defauts: Vec<String> = Vec::new();

    for contrat in CONTRATS {
        println!("cargo:rerun-if-changed={}", contrat.fichier);
        let source = std::fs::read_to_string(racine.join(contrat.fichier))
            .unwrap_or_else(|e| panic!("refus obrain : lecture de {} : {e}", contrat.fichier));
        let fichier = syn::parse_file(&source)
            .unwrap_or_else(|e| panic!("refus obrain : analyse de {} : {e}", contrat.fichier));
        let cible_courte = contrat.cible.rsplit("::").next().unwrap();

        writeln!(
            code,
            "#[allow(unused_imports, unused_variables, clippy::too_many_arguments)]\n\
             pub(crate) mod {} {{\n    use {}::*;",
            contrat.nom, contrat.module
        )
        .unwrap();
        for item in &fichier.items {
            if let syn::Item::Use(u) = item {
                if est_cfg_test(&u.attrs) {
                    continue;
                }
                let ligne = u.to_token_stream().to_string();
                // `use super::x` only means something next to the contract.
                let ligne =
                    ligne.replacen("use super ::", &format!("use {} ::", contrat.parent), 1);
                writeln!(code, "    {ligne}").unwrap();
            }
        }

        for item in &fichier.items {
            let syn::Item::Trait(t) = item else { continue };
            if !t.attrs.iter().any(|a| a.path().is_ident("async_trait")) {
                continue;
            }
            let nom_trait = t.ident.to_string();
            let fait_main = portes
                .iter()
                .any(|(tr, ty)| *tr == nom_trait && ty == cible_courte);

            let mut methodes = String::new();
            for membre in &t.items {
                let syn::TraitItem::Fn(f) = membre else {
                    panic!(
                        "refus obrain : {nom_trait} porte autre chose qu'une méthode \
                         (type ou constante associée) : le générateur ne sait pas le refuser"
                    );
                };
                let nom = format!("{nom_trait}::{}", f.sig.ident);
                if fait_main {
                    portees.push(nom);
                    continue;
                }
                if !rend_un_result(&f.sig.output) {
                    assert!(
                        f.default.is_some(),
                        "refus obrain : {nom} ne rend pas un Result et n'a pas de corps par \
                         défaut : il ne peut ni refuser ni hériter. Écrivez-le à la main dans \
                         {ADAPTATEUR}/."
                    );
                    defauts.push(nom);
                    continue;
                }
                let attrs: String = f
                    .attrs
                    .iter()
                    .filter(|a| !a.path().is_ident("doc"))
                    .map(|a| a.to_token_stream().to_string())
                    .collect::<Vec<_>>()
                    .join(" ");
                writeln!(
                    methodes,
                    "        {attrs} {} {{ Err(crate::obrain::NonPorte(\"{nom}\").into()) }}",
                    f.sig.to_token_stream()
                )
                .unwrap();
                refusees.push(nom);
            }
            if !fait_main {
                writeln!(
                    code,
                    "    #[async_trait::async_trait]\n    impl {nom_trait} for {} {{\n{methodes}    }}",
                    contrat.cible
                )
                .unwrap();
            }
        }
        code.push_str("}\n");
    }

    for (nom, liste, doc) in [
        (
            "REFUSEES",
            &refusees,
            "Every contract method this build refuses by name.",
        ),
        (
            "PORTEES",
            &portees,
            "Every contract method of a trait implemented by hand in src/obrain/.",
        ),
        (
            "DEFAUTS_CONSERVES",
            &defauts,
            "Methods that cannot refuse (no `Result`): the contract's default is kept.",
        ),
    ] {
        writeln!(code, "/// {doc}\npub(crate) const {nom}: &[&str] = &[").unwrap();
        for m in liste {
            writeln!(code, "    \"{m}\",").unwrap();
        }
        code.push_str("];\n");
    }

    std::fs::write(sortie, code)
        .unwrap_or_else(|e| panic!("refus obrain : écriture de {} : {e}", sortie.display()));
}

fn est_cfg_test(attrs: &[syn::Attribute]) -> bool {
    attrs
        .iter()
        .any(|a| a.path().is_ident("cfg") && a.to_token_stream().to_string().contains("test"))
}

fn rend_un_result(sortie: &syn::ReturnType) -> bool {
    let syn::ReturnType::Type(_, ty) = sortie else {
        return false;
    };
    let syn::Type::Path(p) = ty.as_ref() else {
        return false;
    };
    p.path.segments.last().is_some_and(|s| s.ident == "Result")
}

/// Every `impl <Trait> for <Type>` at the top level of the files under `dir`,
/// as `(trait, type)` short names.
fn impls_ecrits_a_la_main(dir: &Path) -> Vec<(String, String)> {
    let mut fichiers: Vec<PathBuf> = Vec::new();
    lister_rs(dir, &mut fichiers);
    let mut out = Vec::new();
    for chemin in fichiers {
        let source = std::fs::read_to_string(&chemin)
            .unwrap_or_else(|e| panic!("refus obrain : lecture de {} : {e}", chemin.display()));
        let fichier = syn::parse_file(&source)
            .unwrap_or_else(|e| panic!("refus obrain : analyse de {} : {e}", chemin.display()));
        for item in fichier.items {
            let syn::Item::Impl(i) = item else { continue };
            let Some((_, chemin_trait, _)) = &i.trait_ else {
                continue;
            };
            let syn::Type::Path(ty) = i.self_ty.as_ref() else {
                continue;
            };
            if let (Some(tr), Some(ty)) = (chemin_trait.segments.last(), ty.path.segments.last()) {
                out.push((tr.ident.to_string(), ty.ident.to_string()));
            }
        }
    }
    out
}

fn lister_rs(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entrees) = std::fs::read_dir(dir) else {
        return;
    };
    for e in entrees.flatten() {
        let p = e.path();
        if p.is_dir() {
            lister_rs(&p, out);
        } else if p.extension().is_some_and(|x| x == "rs") {
            out.push(p);
        }
    }
    out.sort();
}
